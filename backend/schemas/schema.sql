-- ROOM_RENTAL_MANAGEMENT_SYSTEM
-- PostgreSQL schema shared by Android User, Web Admin, and FastAPI.
--
-- IMPORTANT:
-- 1. FastAPI is the only application component that connects to PostgreSQL.
-- 2. Android and Web must call FastAPI; they must never connect to the DB directly.
-- 3. This schema is intended for a NEW PostgreSQL database.
--
-- Run from the repository root after creating the database:
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f backend/schemas/schema.sql

BEGIN;

CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firebase_uid    VARCHAR(128) NOT NULL UNIQUE,
    email           VARCHAR(255) NOT NULL UNIQUE,
    full_name       VARCHAR(150) NOT NULL,
    phone           VARCHAR(30),
    avatar_url      TEXT,
    role            VARCHAR(10) NOT NULL DEFAULT 'USER'
                    CHECK (role IN ('USER', 'ADMIN')),
    status          VARCHAR(10) NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE', 'BLOCKED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS rooms (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200) NOT NULL,
    description     TEXT,
    address         TEXT NOT NULL,
    ward            VARCHAR(120),
    district        VARCHAR(120),
    city            VARCHAR(120) NOT NULL,
    monthly_price   BIGINT NOT NULL CHECK (monthly_price >= 0),
    area_m2         NUMERIC(10, 2)
                    CHECK (area_m2 IS NULL OR area_m2 > 0),
    capacity        INTEGER NOT NULL DEFAULT 1 CHECK (capacity > 0),
    amenities       JSONB NOT NULL DEFAULT '[]'::JSONB
                    CHECK (jsonb_typeof(amenities) = 'array'),
    status          VARCHAR(10) NOT NULL DEFAULT 'AVAILABLE'
                    CHECK (status IN ('AVAILABLE', 'RENTED', 'INACTIVE')),
    created_by      BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE RESTRICT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS room_images (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT NOT NULL
                    REFERENCES rooms(id) ON DELETE CASCADE,
    image_url       TEXT NOT NULL,
    sort_order      INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS rental_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT NOT NULL
                    REFERENCES rooms(id) ON DELETE RESTRICT,
    user_id         BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE RESTRICT,
    message         TEXT,
    desired_move_in DATE,
    status          VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN (
                        'PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'
                    )),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Allows contracts to enforce that room and tenant match the request.
    CONSTRAINT uq_rental_requests_id_room_user
        UNIQUE (id, room_id, user_id)
);

CREATE TABLE IF NOT EXISTS rental_contracts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id      BIGINT NOT NULL UNIQUE,
    room_id         BIGINT NOT NULL,
    tenant_id       BIGINT NOT NULL,
    start_date      DATE NOT NULL,
    end_date        DATE,
    monthly_price   BIGINT NOT NULL CHECK (monthly_price >= 0),
    deposit_amount  BIGINT NOT NULL DEFAULT 0 CHECK (deposit_amount >= 0),
    status          VARCHAR(10) NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE', 'ENDED', 'CANCELLED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_contract_date_range
        CHECK (end_date IS NULL OR end_date >= start_date),

    CONSTRAINT fk_contract_originating_request
        FOREIGN KEY (request_id, room_id, tenant_id)
        REFERENCES rental_requests(id, room_id, user_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_contract_room
        FOREIGN KEY (room_id)
        REFERENCES rooms(id) ON DELETE RESTRICT,

    CONSTRAINT fk_contract_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES users(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id     BIGINT NOT NULL
                    REFERENCES rental_contracts(id) ON DELETE RESTRICT,
    amount          BIGINT NOT NULL CHECK (amount > 0),
    payment_type    VARCHAR(10) NOT NULL
                    CHECK (payment_type IN ('DEPOSIT', 'RENT', 'OTHER')),
    -- For monthly rent use YYYY-MM; NULL for non-periodic payments.
    payment_period  VARCHAR(7)
                    CHECK (
                        payment_period IS NULL
                        OR payment_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'
                    ),
    status          VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'REFUNDED')),
    paid_at         TIMESTAMPTZ,
    note            TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS favorites (
    user_id         BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
    room_id         BIGINT NOT NULL
                    REFERENCES rooms(id) ON DELETE CASCADE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, room_id)
);

CREATE TABLE IF NOT EXISTS activity_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id        BIGINT
                    REFERENCES users(id) ON DELETE SET NULL,
    action          VARCHAR(100) NOT NULL,
    target_type     VARCHAR(50),
    target_id       BIGINT,
    details         JSONB,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- One pending request per user per room.
CREATE UNIQUE INDEX IF NOT EXISTS uq_pending_request_per_user_room
    ON rental_requests(user_id, room_id)
    WHERE status = 'PENDING';

-- At most one active contract per room.
CREATE UNIQUE INDEX IF NOT EXISTS uq_active_contract_per_room
    ON rental_contracts(room_id)
    WHERE status = 'ACTIVE';

CREATE INDEX IF NOT EXISTS idx_rooms_status_city
    ON rooms(status, city);

CREATE INDEX IF NOT EXISTS idx_rooms_price
    ON rooms(monthly_price);

CREATE INDEX IF NOT EXISTS idx_requests_user_status_created
    ON rental_requests(user_id, status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_requests_room_status
    ON rental_requests(room_id, status);

CREATE INDEX IF NOT EXISTS idx_contracts_tenant_status
    ON rental_contracts(tenant_id, status);

CREATE INDEX IF NOT EXISTS idx_payments_contract_status
    ON payments(contract_id, status);

CREATE INDEX IF NOT EXISTS idx_room_images_room_sort
    ON room_images(room_id, sort_order, id);

-- Automatically update updated_at when a row is changed.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_rooms_updated_at ON rooms;
CREATE TRIGGER trg_rooms_updated_at
    BEFORE UPDATE ON rooms
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_rental_requests_updated_at ON rental_requests;
CREATE TRIGGER trg_rental_requests_updated_at
    BEFORE UPDATE ON rental_requests
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_rental_contracts_updated_at ON rental_contracts;
CREATE TRIGGER trg_rental_contracts_updated_at
    BEFORE UPDATE ON rental_contracts
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;
