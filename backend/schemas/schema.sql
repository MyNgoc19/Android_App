-- =====================================================================
-- ROOM_RENTAL_MANAGEMENT_SYSTEM
-- PostgreSQL schema dùng chung cho Android User, Web Admin và FastAPI.
--
-- QUAN TRỌNG:
-- 1. Chỉ FastAPI kết nối PostgreSQL. Android và Web gọi FastAPI, không kết nối DB trực tiếp.
-- 2. Dùng được cho CẢ database mới LẪN database đang có dữ liệu (tạo từ schema gốc):
--    tự tạo bảng còn thiếu, tự thêm cột còn thiếu, KHÔNG xóa dữ liệu.
--    Chạy lại nhiều lần vẫn an toàn.
-- 3. Các bảng/cột đánh dấu [MỚI] là phần bổ sung cho các màn hình của app người thuê:
--    loại phòng + giá điện nước, lịch hẹn xem phòng, chỉ số điện nước, người thuê báo
--    đã thanh toán, yêu cầu sửa chữa, yêu cầu trả phòng, thông tin nhận tiền.
--    Backend cần thêm model + API cho các phần [MỚI] thì app mới dùng được.
--
-- Chạy:
--   pgAdmin 4: chuột phải database > Query Tool > mở file này > Execute (F5)
--   hoặc:      psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f backend/schemas/schema.sql
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. USERS: tài khoản (đồng bộ từ Firebase qua POST /auth/session)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firebase_uid    VARCHAR(128) NOT NULL UNIQUE,
    email           VARCHAR(255) NOT NULL UNIQUE,
    full_name       VARCHAR(150) NOT NULL,
    phone           VARCHAR(30),
    avatar_url      TEXT,
    gender          VARCHAR(10)                                   -- [MỚI] màn Sửa hồ sơ
                    CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE', 'OTHER')),
    role            VARCHAR(10) NOT NULL DEFAULT 'USER'
                    CHECK (role IN ('USER', 'ADMIN')),
    status          VARCHAR(10) NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE', 'BLOCKED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 2. ROOMS + ROOM_IMAGES
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS rooms (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(200) NOT NULL,
    description         TEXT,
    room_type           VARCHAR(10) NOT NULL DEFAULT 'ROOM'       -- [MỚI] lọc Phòng trọ / Căn hộ
                        CHECK (room_type IN ('ROOM', 'APARTMENT')),
    address             TEXT NOT NULL,
    ward                VARCHAR(120),
    district            VARCHAR(120),
    city                VARCHAR(120) NOT NULL,
    monthly_price       BIGINT NOT NULL CHECK (monthly_price >= 0),
    deposit_amount      BIGINT NOT NULL DEFAULT 0                 -- [MỚI] tiền cọc dự kiến
                        CHECK (deposit_amount >= 0),
    electricity_price   BIGINT NOT NULL DEFAULT 3500              -- [MỚI] đ/kWh
                        CHECK (electricity_price >= 0),
    water_price         BIGINT NOT NULL DEFAULT 20000             -- [MỚI] đ/m3
                        CHECK (water_price >= 0),
    service_fee         BIGINT NOT NULL DEFAULT 0                 -- [MỚI] đ/tháng
                        CHECK (service_fee >= 0),
    area_m2             NUMERIC(10, 2)
                        CHECK (area_m2 IS NULL OR area_m2 > 0),
    capacity            INTEGER NOT NULL DEFAULT 1 CHECK (capacity > 0),
    amenities           JSONB NOT NULL DEFAULT '[]'::JSONB
                        CHECK (jsonb_typeof(amenities) = 'array'),
    status              VARCHAR(10) NOT NULL DEFAULT 'AVAILABLE'
                        CHECK (status IN ('AVAILABLE', 'RENTED', 'INACTIVE')),
    created_by          BIGINT NOT NULL
                        REFERENCES users(id) ON DELETE RESTRICT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS room_images (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT NOT NULL
                    REFERENCES rooms(id) ON DELETE CASCADE,
    image_url       TEXT NOT NULL,
    sort_order      INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 3. FAVORITES: phòng yêu thích
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS favorites (
    user_id         BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
    room_id         BIGINT NOT NULL
                    REFERENCES rooms(id) ON DELETE CASCADE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, room_id)
);

-- ---------------------------------------------------------------------
-- 4. VIEWING_APPOINTMENTS [MỚI]: đặt lịch xem phòng
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS viewing_appointments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT NOT NULL
                    REFERENCES rooms(id) ON DELETE RESTRICT,
    user_id         BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE RESTRICT,
    scheduled_at    TIMESTAMPTZ NOT NULL,
    note            TEXT,
    status          VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELLED', 'DONE')),
    admin_note      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 5. RENTAL_REQUESTS: yêu cầu thuê ("Đồng ý thuê" trên app)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS rental_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT NOT NULL
                    REFERENCES rooms(id) ON DELETE RESTRICT,
    user_id         BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE RESTRICT,
    message         TEXT,
    desired_move_in DATE,
    status          VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN (
                        'PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'
                    )),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Cho phép hợp đồng ràng buộc đúng phòng + đúng người của yêu cầu
    CONSTRAINT uq_rental_requests_id_room_user
        UNIQUE (id, room_id, user_id)
);

-- ---------------------------------------------------------------------
-- 6. RENTAL_CONTRACTS: hợp đồng (admin tạo sau khi duyệt yêu cầu)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS rental_contracts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id      BIGINT NOT NULL UNIQUE,
    room_id         BIGINT NOT NULL,
    tenant_id       BIGINT NOT NULL,
    start_date      DATE NOT NULL,
    end_date        DATE,
    monthly_price   BIGINT NOT NULL CHECK (monthly_price >= 0),
    deposit_amount  BIGINT NOT NULL DEFAULT 0 CHECK (deposit_amount >= 0),
    terms           TEXT,                                         -- [MỚI] điều khoản hiển thị cho người thuê
    status          VARCHAR(10) NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE', 'ENDED', 'CANCELLED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_contract_date_range
        CHECK (end_date IS NULL OR end_date >= start_date),

    CONSTRAINT fk_contract_originating_request
        FOREIGN KEY (request_id, room_id, tenant_id)
        REFERENCES rental_requests(id, room_id, user_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_contract_room
        FOREIGN KEY (room_id)
        REFERENCES rooms(id) ON DELETE RESTRICT,

    CONSTRAINT fk_contract_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES users(id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 7. PAYMENTS: tiền cọc, tiền thuê, khoản khác
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id         BIGINT NOT NULL
                        REFERENCES rental_contracts(id) ON DELETE RESTRICT,
    amount              BIGINT NOT NULL CHECK (amount > 0),
    payment_type        VARCHAR(10) NOT NULL
                        CHECK (payment_type IN ('DEPOSIT', 'RENT', 'OTHER')),
    -- Tiền thuê hằng tháng dùng YYYY-MM; NULL với khoản không theo kỳ
    payment_period      VARCHAR(7)
                        CHECK (
                            payment_period IS NULL
                            OR payment_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'
                        ),
    due_date            DATE,                                     -- [MỚI] hạn thanh toán
    -- PENDING: chưa trả | PROCESSING [MỚI]: người thuê báo đã chuyển, chờ admin xác nhận
    -- PAID: đã nhận tiền | FAILED | REFUNDED
    status              VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                        CHECK (status IN ('PENDING', 'PROCESSING', 'PAID', 'FAILED', 'REFUNDED')),
    method              VARCHAR(15)                               -- [MỚI] người thuê chọn khi báo đã trả
                        CHECK (method IS NULL OR method IN ('BANK_TRANSFER', 'CASH', 'MOMO')),
    transaction_code    VARCHAR(100),                             -- [MỚI] mã giao dịch ngân hàng
    submitted_at        TIMESTAMPTZ,                              -- [MỚI] lúc người thuê báo đã trả
    paid_at             TIMESTAMPTZ,
    note                TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),       -- [MỚI]

    -- Đã PAID thì phải có thời điểm thanh toán
    CONSTRAINT ck_payment_paid_at
        CHECK (status <> 'PAID' OR paid_at IS NOT NULL),
    -- Tiền thuê phải có kỳ thanh toán
    CONSTRAINT ck_rent_has_period
        CHECK (payment_type <> 'RENT' OR payment_period IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- 8. METER_READINGS [MỚI]: chỉ số điện / nước theo tháng (hiển thị trên hóa đơn)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meter_readings (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id         BIGINT NOT NULL
                        REFERENCES rental_contracts(id) ON DELETE RESTRICT,
    payment_id          BIGINT UNIQUE                             -- khoản RENT của tháng đó
                        REFERENCES payments(id) ON DELETE SET NULL,
    period              VARCHAR(7) NOT NULL
                        CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    electricity_old     INTEGER NOT NULL CHECK (electricity_old >= 0),
    electricity_new     INTEGER NOT NULL,
    water_old           INTEGER NOT NULL CHECK (water_old >= 0),
    water_new           INTEGER NOT NULL,
    -- Lưu đơn giá tại thời điểm chốt để hóa đơn cũ không đổi khi phòng đổi giá
    electricity_price   BIGINT NOT NULL CHECK (electricity_price >= 0),
    water_price         BIGINT NOT NULL CHECK (water_price >= 0),
    recorded_by         BIGINT
                        REFERENCES users(id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_meter_increase
        CHECK (electricity_new >= electricity_old AND water_new >= water_old),
    CONSTRAINT uq_meter_contract_period
        UNIQUE (contract_id, period)
);

-- ---------------------------------------------------------------------
-- 9. MAINTENANCE_REQUESTS [MỚI]: yêu cầu sửa chữa
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS maintenance_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id     BIGINT NOT NULL
                    REFERENCES rental_contracts(id) ON DELETE RESTRICT,
    user_id         BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE RESTRICT,
    title           VARCHAR(200) NOT NULL,
    description     TEXT NOT NULL,
    priority        VARCHAR(10) NOT NULL DEFAULT 'MEDIUM'
                    CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    image_url       TEXT,                                         -- ảnh hư hỏng (Cloudinary)
    status          VARCHAR(12) NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN ('PENDING', 'IN_PROGRESS', 'DONE', 'REJECTED', 'CANCELLED')),
    admin_note      TEXT,
    resolved_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 10. MOVE_OUT_REQUESTS [MỚI]: yêu cầu trả phòng
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS move_out_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id     BIGINT NOT NULL
                    REFERENCES rental_contracts(id) ON DELETE RESTRICT,
    user_id         BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE RESTRICT,
    move_out_date   DATE NOT NULL,
    reason          TEXT,
    status          VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'COMPLETED')),
    admin_note      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 11. PAYMENT_ACCOUNTS [MỚI]: tài khoản nhận tiền (hiện ở màn Đặt cọc / Thanh toán)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS payment_accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method          VARCHAR(15) NOT NULL
                    CHECK (method IN ('BANK_TRANSFER', 'MOMO')),
    bank_name       VARCHAR(100),
    account_number  VARCHAR(50) NOT NULL,
    account_holder  VARCHAR(150) NOT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 12. ACTIVITY_LOGS: nhật ký thao tác
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS activity_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id        BIGINT
                    REFERENCES users(id) ON DELETE SET NULL,
    action          VARCHAR(100) NOT NULL,
    target_type     VARCHAR(50),
    target_id       BIGINT,
    details         JSONB,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =====================================================================
-- NÂNG CẤP DATABASE CŨ: thêm các cột [MỚI] nếu bảng đã tồn tại từ trước
-- (database mới thì các cột đã có, các lệnh dưới tự bỏ qua)
-- =====================================================================
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS gender VARCHAR(10)
        CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE', 'OTHER'));

ALTER TABLE rooms
    ADD COLUMN IF NOT EXISTS room_type VARCHAR(10) NOT NULL DEFAULT 'ROOM'
        CHECK (room_type IN ('ROOM', 'APARTMENT')),
    ADD COLUMN IF NOT EXISTS deposit_amount BIGINT NOT NULL DEFAULT 0
        CHECK (deposit_amount >= 0),
    ADD COLUMN IF NOT EXISTS electricity_price BIGINT NOT NULL DEFAULT 3500
        CHECK (electricity_price >= 0),
    ADD COLUMN IF NOT EXISTS water_price BIGINT NOT NULL DEFAULT 20000
        CHECK (water_price >= 0),
    ADD COLUMN IF NOT EXISTS service_fee BIGINT NOT NULL DEFAULT 0
        CHECK (service_fee >= 0);

ALTER TABLE rental_contracts
    ADD COLUMN IF NOT EXISTS terms TEXT;

ALTER TABLE payments
    ADD COLUMN IF NOT EXISTS due_date DATE,
    ADD COLUMN IF NOT EXISTS method VARCHAR(15)
        CHECK (method IS NULL OR method IN ('BANK_TRANSFER', 'CASH', 'MOMO')),
    ADD COLUMN IF NOT EXISTS transaction_code VARCHAR(100),
    ADD COLUMN IF NOT EXISTS submitted_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

-- Trạng thái thanh toán: thêm PROCESSING (người thuê báo đã chuyển, chờ admin xác nhận)
ALTER TABLE payments DROP CONSTRAINT IF EXISTS payments_status_check;
ALTER TABLE payments ADD CONSTRAINT payments_status_check
    CHECK (status IN ('PENDING', 'PROCESSING', 'PAID', 'FAILED', 'REFUNDED'));

-- 2 ràng buộc mới cho payments: NOT VALID = chỉ kiểm tra dữ liệu thêm/sửa từ nay,
-- không làm lỗi khi database cũ lỡ có dòng chưa đúng
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_payment_paid_at') THEN
        ALTER TABLE payments ADD CONSTRAINT ck_payment_paid_at
            CHECK (status <> 'PAID' OR paid_at IS NOT NULL) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_rent_has_period') THEN
        ALTER TABLE payments ADD CONSTRAINT ck_rent_has_period
            CHECK (payment_type <> 'RENT' OR payment_period IS NOT NULL) NOT VALID;
    END IF;
END;
$$;

