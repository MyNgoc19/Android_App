-- =====================================================================
-- RÀNG BUỘC NGHIỆP VỤ (unique index có điều kiện)
-- =====================================================================

-- Email không phân biệt hoa/thường (A@gmail.com = a@gmail.com)
-- (nếu dữ liệu cũ đang có email trùng hoa/thường thì chỉ báo NOTICE, không dừng file)
DO $$
BEGIN
    CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower ON users(LOWER(email));
EXCEPTION WHEN unique_violation THEN
    RAISE NOTICE 'Bỏ qua uq_users_email_lower: đang có email trùng hoa/thường trong bảng users';
END;
$$;

-- Mỗi người chỉ có 1 yêu cầu thuê đang chờ cho mỗi phòng
CREATE UNIQUE INDEX IF NOT EXISTS uq_pending_request_per_user_room
    ON rental_requests(user_id, room_id)
    WHERE status = 'PENDING';

-- Mỗi phòng tối đa 1 hợp đồng đang hiệu lực
CREATE UNIQUE INDEX IF NOT EXISTS uq_active_contract_per_room
    ON rental_contracts(room_id)
    WHERE status = 'ACTIVE';

-- Mỗi hợp đồng chỉ có 1 khoản tiền thuê CHƯA HỦY (PENDING/PAID) cho mỗi tháng.
-- Khớp với backend admin.py: khoản FAILED/REFUNDED được phép tạo lại cho cùng tháng.
DROP INDEX IF EXISTS uq_rent_per_contract_period;
CREATE UNIQUE INDEX uq_rent_per_contract_period
    ON payments(contract_id, payment_period)
    WHERE payment_type = 'RENT' AND status IN ('PENDING', 'PAID');

-- Mỗi người chỉ có 1 lịch hẹn đang chờ/đã xác nhận cho mỗi phòng
CREATE UNIQUE INDEX IF NOT EXISTS uq_open_appointment_per_user_room
    ON viewing_appointments(user_id, room_id)
    WHERE status IN ('PENDING', 'CONFIRMED');

-- Mỗi hợp đồng chỉ có 1 yêu cầu trả phòng đang chờ/đã duyệt
CREATE UNIQUE INDEX IF NOT EXISTS uq_open_move_out_per_contract
    ON move_out_requests(contract_id)
    WHERE status IN ('PENDING', 'APPROVED');

